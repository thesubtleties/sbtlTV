// Run: pnpm --filter @sbtltv/ui gen:teams   (or: node packages/ui/scripts/generate-teams-data.mjs)
// Fetches team metadata + logos from ESPN's public API and writes a bundled
// teams-data.ts. Run MANUALLY when team lists change (relocations/rebrands,
// new college teams); the output is committed.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const LEAGUES = [
  { id: 'nfl', sport: 'football', slug: 'nfl' },
  { id: 'nba', sport: 'basketball', slug: 'nba' },
  { id: 'mlb', sport: 'baseball', slug: 'mlb' },
  { id: 'nhl', sport: 'hockey', slug: 'nhl' },
  { id: 'cfb', sport: 'football', slug: 'college-football' },
  { id: 'cbb', sport: 'basketball', slug: 'mens-college-basketball' },
];

async function fetchLeague(l) {
  const url = `https://site.api.espn.com/apis/site/v2/sports/${l.sport}/${l.slug}/teams?limit=1000`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${l.id}: HTTP ${res.status}`);
  const json = await res.json();
  const teams = json?.sports?.[0]?.leagues?.[0]?.teams ?? [];
  return teams
    .map(({ team }) => ({
      leagueId: l.id,
      location: team.location ?? '',
      nickname: team.name ?? team.shortDisplayName ?? '',
      displayName: team.displayName ?? '',
      abbrev: (team.abbreviation ?? '').toUpperCase(),
      logoUrl: team.logos?.[0]?.href ?? '',
    }))
    // Teams without a logo can't render a matchup; drop them (fail silent).
    .filter((t) => t.displayName && t.logoUrl);
}

const data = {};
const counts = [];
for (const l of LEAGUES) {
  process.stderr.write(`Fetching ${l.id}...\n`);
  data[l.id] = await fetchLeague(l);
  counts.push(`${l.id}=${data[l.id].length}`);
  process.stderr.write(`  ${data[l.id].length} teams (with logos)\n`);
}

const header =
  `// AUTO-GENERATED by scripts/generate-teams-data.mjs — do not edit by hand.\n` +
  `// Generated: ${new Date().toISOString()} from ESPN public API.\n` +
  `// Teams per league (after logo filter): ${counts.join(' ')}\n` +
  `// Regenerate: pnpm --filter @sbtltv/ui gen:teams\n` +
  `import type { TeamsData } from './types';\n\n`;

const body = `${header}export const TEAMS_DATA: TeamsData = ${JSON.stringify(data, null, 2)};\n`;

const here = dirname(fileURLToPath(import.meta.url));
const dest = join(here, '..', 'src', 'services', 'sports', 'teams-data.ts');
writeFileSync(dest, body);
process.stderr.write(`Wrote ${dest}\n`);
